// Addition
int math_Add(int n1, int n2){
	return n1 + n2;


}

//Substraction
int math_sub(int n1, int n2 ){

	return n1-n2;
}

//Multiplication
int math_mul(int n1, int n2){

	return n1 *n2;

}

//Division
float math_div(int n1, int n2){

	return (float) n1/n2;
}


